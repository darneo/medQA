"""Error analysis on the held-out test: base vs medbot_old on the same questions -> docs/ERROR_ANALYSIS_EXAMPLES.md

    .venv\\Scripts\\python.exe scripts\\harness_report.py      # writes results/harness/per_question_answers.jsonl
    .venv\\Scripts\\python.exe scripts\\error_analysis.py

Selected automatically (no cherry-picking by hand):
  - largest improvements and largest regressions of medbot_old over base (semantic similarity, ties by chrF);
  - degenerate output: repetition loops, answers cut at the 512-token limit, wrong language;
  - a fixed random sample (seed 42) for manual annotation: results/annotation/sample_to_annotate.csv.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from medqa.evaluation import repeated_share  # noqa: E402
from medqa.text import detect_language, tokens  # noqa: E402

SRC = ROOT / "results" / "harness" / "per_question_answers.jsonl"
OUT = ROOT / "docs" / "ERROR_ANALYSIS_EXAMPLES.md"
ANN = ROOT / "results" / "annotation"
CUT = 700


def short(text: str, n: int = CUT) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[:n].rsplit(" ", 1)[0] + " […]"


def block(r: pd.Series, title: str) -> list[str]:
    seen = "disease seen in train (other question type)" if r.seen_focus else "unseen disease"
    return [f"### {title}", "",
            f"**[{r.lang}] {r.q}** — test row {r.row}, {seen}", "",
            f"- **Reference:** {short(r.ref, 450)}",
            f"- **base** (chrF {r.chrf_s_b:.1f}, semantic {r.semantic_b:.3f}): {short(r.answer_b)}",
            f"- **medbot_old** (chrF {r.chrf_s:.1f}, semantic {r.semantic:.3f}): {short(r.answer)}", ""]


def flags(answer: str, lang: str) -> list[str]:
    words = tokens(answer)
    out = []
    if repeated_share(words) > 0.2:
        out.append(f"repetition {repeated_share(words):.0%}")
    if detect_language(answer) != lang:
        out.append(f"wrong language ({detect_language(answer)})")
    if len(words) >= 330:
        out.append("very long / likely cut at token limit")
    return out


def main() -> None:
    df = pd.read_json(SRC, lines=True)
    test = df[(df.split == "test") & (df.variant == "medquad")]
    base, mb = test[test.model == "base"], test[test.model == "medbot_old"]
    m = mb.merge(base[["lang", "row", "answer", "chrf_s", "semantic", "rougeL"]], on=["lang", "row"], suffixes=("", "_b"))
    if m.empty:
        sys.exit("no paired base / medbot_old test answers yet")
    m["d_sem"], m["d_chrf"] = m.semantic - m.semantic_b, m.chrf_s - m.chrf_s_b
    m["flags_b"] = [flags(a, l) for a, l in zip(m.answer_b, m.lang)]
    m["flags_m"] = [flags(a, l) for a, l in zip(m.answer, m.lang)]

    text = ["# Error analysis — held-out test, base vs medbot_old", "",
            f"Generated by `scripts/error_analysis.py` from `{SRC.relative_to(ROOT).as_posix()}`. "
            f"{len(m)} paired test questions (same question, same prompt, greedy decoding). Answers are shortened to "
            f"{CUT} characters here; full text is in the JSONL. Examples are selected by rule, not by hand.", ""]

    improved = (m.d_sem > 0).mean()
    text += ["## Overview", "",
             f"- medbot_old is closer in meaning to the reference than base on **{improved:.0%}** of questions "
             f"(by language: " + ", ".join(f"{l} {(g.d_sem > 0).mean():.0%}" for l, g in m.groupby('lang', sort=False))
             + ").",
             f"- Degenerate answers (repetition > 20 %, wrong language, or ≥ 330 words): "
             f"base **{sum(bool(f) for f in m.flags_b)}**, medbot_old **{sum(bool(f) for f in m.flags_m)}** of {len(m)}.",
             ""]
    by = []
    for lang, g in m.groupby("lang", sort=False):
        by.append(f"| {lang} | {len(g)} | {sum(bool(f) for f in g.flags_b)} | {sum(bool(f) for f in g.flags_m)} | "
                  f"{(g.d_sem > 0).mean():.0%} |")
    text += ["| lang | n | degenerate: base | degenerate: medbot_old | medbot_old closer in meaning |",
             "|---|---|---|---|---|", *by, ""]

    text += ["## 1. Largest improvements after training", ""]
    for _, r in m.sort_values(["d_sem", "d_chrf"], ascending=False).head(4).iterrows():
        text += block(r, f"Δ semantic {r.d_sem:+.3f}, Δ chrF {r.d_chrf:+.1f}")
    text += ["## 2. Largest regressions after training", ""]
    for _, r in m.sort_values(["d_sem", "d_chrf"]).head(4).iterrows():
        text += block(r, f"Δ semantic {r.d_sem:+.3f}, Δ chrF {r.d_chrf:+.1f}")
    text += ["## 3. Degenerate outputs", ""]
    for col, who in (("flags_b", "base"), ("flags_m", "medbot_old")):
        bad = m[m[col].map(bool)]
        for lang in ("kk", "ru", "en"):
            sel = bad[bad.lang == lang].head(1)
            for _, r in sel.iterrows():
                text += block(r, f"{who}: {', '.join(r[col])}")
    OUT.write_text("\n".join(text), encoding="utf-8")

    ANN.mkdir(parents=True, exist_ok=True)
    sample = m.groupby("lang", sort=False).sample(n=10, random_state=42)
    long = pd.concat([sample.assign(system="base", ans=sample.answer_b), sample.assign(system="medbot_old",
                                                                                      ans=sample.answer)])
    long[["lang", "row", "q", "ref", "system", "ans"]].rename(columns={"ans": "answer"}).to_csv(
        ANN / "sample_to_annotate.csv", index=False, encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)} and {ANN.relative_to(ROOT)}/sample_to_annotate.csv ({len(long)} answers)")


if __name__ == "__main__":
    main()
